/*************************************************************************************************************
 * VCDio example: an ISO 9141-2 K-line session as a waveform.
 *
 *   5-baud init (address 0x33) -> sync 0x55, key bytes 08 08 -> ~KB2 -> ~address
 *   OBD request "PIDs supported 01-20" -> ECU response -> one corrupted frame
 *
 * Output: kline_example.vcd (or the path given as first argument).
 *   PulseView: import it, add a UART decoder on tx/rx at 10400 baud (and one at 5 baud for the init byte).
 *   GTKWave/Surfer: tx_data/rx_data show the bytes and 'state' shows the session phase.
 *
 * Sorted mode is used so the tester and ECU sides can each be written in one go, out of time order.
 *************************************************************************************************************/

/* ================================================ INCLUDES =============================================== */
#include "vcd_io.h"
#include <stdio.h>

/* ================================================= MACROS ================================================ */
#define MS(x) ((vcdTime_t)(x) * 1000u) /* timescale is 1 us */

#define CHECKED(expr)                                                                                       \
    do                                                                                                      \
    {                                                                                                       \
        vcdStatus_t st_ = (expr);                                                                           \
        if (st_ != VCD_OK)                                                                                  \
        {                                                                                                   \
            fprintf(stderr, "%s:%d: %s: %s\n", __FILE__, __LINE__, #expr, VCD_StatusStr(st_));              \
            return 1;                                                                                       \
        }                                                                                                   \
    } while (0)

/* ================================================ ENTRY POINT ============================================ */
int main(int argc, char **argv)
{
    static const uint8_t keyBytes[] = {0x55u, 0x08u, 0x08u};
    static const uint8_t request[] = {0x68u, 0x6Au, 0xF1u, 0x01u, 0x00u, 0xC4u};
    static const uint8_t response[] = {0x48u, 0x6Bu, 0x10u, 0x41u, 0x00u, 0xBEu, 0x3Eu, 0xB8u, 0x11u, 0xC9u};
    const char *path = (argc > 1) ? argv[1] : "kline_example.vcd";
    vcdWriterConfig_t cfg;
    vcdUartConfig_t fastTx;
    vcdUartConfig_t fastRx;
    vcdUartConfig_t slowTx;
    vcdWriter_t *w = NULL;
    vcdSignal_t tx;
    vcdSignal_t rx;
    vcdSignal_t txData;
    vcdSignal_t rxData;
    vcdSignal_t state;
    vcdTime_t t;
    vcdTime_t initEnd;
    vcdTime_t syncEnd;
    vcdTime_t invKb2End;
    vcdTime_t invAddrEnd;
    vcdTime_t requestEnd;
    vcdTime_t responseEnd;
    vcdTime_t errorEnd;

    VCD_WriterConfigDefault(&cfg);
    cfg.timescale.magnitude = 1u;
    cfg.timescale.unit = VCD_UNIT_US;
    cfg.order = VCD_ORDER_SORTED;
    cfg.comment = "ISO 9141-2 5-baud init and one OBD request, generated by the VCDio example";
    CHECKED(VCD_WriterOpenFile(&w, path, &cfg));

    CHECKED(VCD_ScopeBegin(w, "kline"));
    CHECKED(VCD_AddVar(w, VCD_VAR_WIRE, 1u, "tx", &tx));
    CHECKED(VCD_AddVar(w, VCD_VAR_WIRE, 1u, "rx", &rx));
    CHECKED(VCD_AddVar(w, VCD_VAR_WIRE, 8u, "tx_data[7:0]", &txData));
    CHECKED(VCD_AddVar(w, VCD_VAR_WIRE, 8u, "rx_data[7:0]", &rxData));
    CHECKED(VCD_AddVar(w, VCD_VAR_STRING, 0u, "state", &state));
    CHECKED(VCD_ScopeEnd(w));

    VCD_UartConfigDefault(&fastTx, cfg.timescale, 10400.0);
    fastRx = fastTx;
    fastTx.dataSignal = txData;
    fastRx.dataSignal = rxData;
    VCD_UartConfigDefault(&slowTx, cfg.timescale, 5.0);
    slowTx.dataSignal = txData;

    /* ---- Tester side (tx) ---- */
    CHECKED(VCD_UartWriteIdle(w, tx, 0u, &fastTx));
    CHECKED(VCD_UartWriteFrame(w, tx, MS(300), 0x33u, &slowTx, 0u, &initEnd));      /* W0 idle, 5 baud */
    syncEnd = initEnd + MS(60) + 3u * VCD_UartFrameTicks(&fastRx) + MS(20);           /* W1 + 3 bytes + W2/W3 */
    CHECKED(VCD_UartWriteFrame(w, tx, syncEnd + MS(30), 0xF7u, &fastTx, 0u, &invKb2End)); /* W4, ~KB2 */
    invAddrEnd = invKb2End + MS(30) + VCD_UartFrameTicks(&fastRx);
    CHECKED(VCD_UartWriteBytes(w, tx, invAddrEnd + MS(55), request, sizeof request, MS(5), &fastTx, &requestEnd));

    /* ---- ECU side (rx), written after the tester although it is earlier in time ---- */
    CHECKED(VCD_UartWriteIdle(w, rx, 0u, &fastRx));
    t = initEnd + MS(60);
    CHECKED(VCD_UartWriteFrame(w, rx, t, keyBytes[0], &fastRx, 0u, &t));
    CHECKED(VCD_UartWriteFrame(w, rx, t + MS(10), keyBytes[1], &fastRx, 0u, &t));
    CHECKED(VCD_UartWriteFrame(w, rx, t + MS(10), keyBytes[2], &fastRx, 0u, &t));
    CHECKED(VCD_UartWriteFrame(w, rx, invKb2End + MS(30), 0xCCu, &fastRx, 0u, NULL)); /* ~address */
    CHECKED(VCD_UartWriteBytes(w, rx, requestEnd + MS(30), response, sizeof response, MS(1), &fastRx, &responseEnd));
    CHECKED(VCD_UartWriteFrame(w, rx, responseEnd + MS(20), 0x5Au, &fastRx, VCD_UART_FLAG_FRAMING_ERROR, &errorEnd));

    /* ---- Session phases ---- */
    CHECKED(VCD_ChangeString(w, state, 0u, "IDLE"));
    CHECKED(VCD_ChangeString(w, state, MS(300), "5BAUD_ADDRESS"));
    CHECKED(VCD_ChangeString(w, state, initEnd, "WAIT_SYNC"));
    CHECKED(VCD_ChangeString(w, state, initEnd + MS(60), "KEY_BYTES"));
    CHECKED(VCD_ChangeString(w, state, syncEnd + MS(30), "INVERTED_KB2"));
    CHECKED(VCD_ChangeString(w, state, invKb2End + MS(30), "INVERTED_ADDRESS"));
    CHECKED(VCD_ChangeString(w, state, invAddrEnd, "READY"));
    CHECKED(VCD_ChangeString(w, state, invAddrEnd + MS(55), "REQUEST"));
    CHECKED(VCD_ChangeString(w, state, requestEnd + MS(30), "RESPONSE"));
    CHECKED(VCD_ChangeString(w, state, responseEnd + MS(20), "CORRUPTED_FRAME"));
    CHECKED(VCD_ChangeString(w, state, errorEnd, "IDLE"));

    CHECKED(VCD_WriterClose(w, errorEnd + MS(50)));
    printf("wrote %s\n", path);
    return 0;
}
